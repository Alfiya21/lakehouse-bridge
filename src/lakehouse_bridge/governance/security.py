"""Row- and column-level security.

Local mode: each role gets its own physically separate DuckDB file that contains only the rows
and (masked) columns it may see, so an agent connected as that role cannot bypass the policy
by writing a fully qualified table name.

BigQuery mode: `bigquery_ddl()` renders equivalent CREATE ROW ACCESS POLICY statements and
masked authorized views. (Rendered here and unit-tested as text; apply them in a real project.)
"""
import duckdb
import yaml
from .. import config as C
from . import catalog

POLICY = C.ROOT / "governance" / "policy.yaml"

MASKS = {  # dialect -> pii kind -> expression template
    "duckdb": {"EMAIL": "'***@' || split_part({c}, '@', 2)", "PHONE": "'***' || right({c}, 4)",
               "PERSON_NAME": "left({c}, 1) || '***'", "DEFAULT": "substr(md5(CAST({c} AS VARCHAR)), 1, 8)"},
    "bigquery": {"EMAIL": "CONCAT('***@', SPLIT({c}, '@')[SAFE_OFFSET(1)])", "PHONE": "CONCAT('***', RIGHT({c}, 4))",
                 "PERSON_NAME": "CONCAT(LEFT({c}, 1), '***')", "DEFAULT": "SUBSTR(TO_HEX(MD5(CAST({c} AS STRING))), 1, 8)"},
}


def load_policy() -> dict:
    return yaml.safe_load(POLICY.read_text())


def _select_list(table_meta: dict, mask: bool, dialect: str) -> str:
    parts = []
    for c in table_meta["columns"]:
        cl = c["classification"]
        if mask and cl:
            expr = MASKS[dialect].get(cl["pii"], MASKS[dialect]["DEFAULT"]).format(c=c["name"])
            parts.append(f"{expr} AS {c['name']}")
        else:
            parts.append(c["name"])
    return ", ".join(parts)


def role_db_path(role: str):
    return C.WAREHOUSE if role == "admin" else C.DATA / f"warehouse_{role}.duckdb"


def build_role_databases() -> dict:
    pol, cat = load_policy(), catalog.build()
    admin = duckdb.connect(str(C.WAREHOUSE), read_only=True)
    summary = {}
    for role, spec in pol["roles"].items():
        if role == "admin":
            continue
        path = role_db_path(role)
        if path.exists():
            path.unlink()
        con = duckdb.connect(str(path))
        con.execute(f"CREATE SCHEMA {C.SCHEMA}")
        n_tables = 0
        for t, meta in cat["tables"].items():
            if t in pol.get("restricted_tables", []):
                continue
            has_region = any(c["name"] == "region" for c in meta["columns"])
            where = f"WHERE {spec['row_filter']}" if (spec["row_filter"] and has_region) else ""
            df = admin.execute(f"SELECT {_select_list(meta, spec['mask_pii'], 'duckdb')} FROM {C.SCHEMA}.{t} {where}").df()
            con.register("_df", df)
            con.execute(f"CREATE TABLE {C.SCHEMA}.{t} AS SELECT * FROM _df")
            con.unregister("_df")
            n_tables += 1
        con.close()
        summary[role] = {"tables": n_tables, "path": str(path)}
    admin.close()
    return summary


def bigquery_ddl(project: str = "PROJECT", dataset: str = "lakehouse_bridge") -> str:
    pol = load_policy()
    cat = (C.REPORTS / "catalog.json")
    import json
    meta_all = json.loads(cat.read_text())["tables"]
    out = ["-- Generated by lakehouse_bridge.governance.security.bigquery_ddl()",
           "-- Review, then apply with: bq query --use_legacy_sql=false < bigquery_governance.sql", ""]
    for role, spec in pol["roles"].items():
        if role == "admin":
            continue
        grantee = f"group:{role.replace('_', '-')}@example.com"
        view_ds = f"{dataset}_{role}"
        out.append(f"CREATE SCHEMA IF NOT EXISTS `{project}.{view_ds}`;")
        for t, meta in meta_all.items():
            if t in pol.get("restricted_tables", []):
                continue
            has_region = any(c["name"] == "region" for c in meta["columns"])
            where = f"WHERE {spec['row_filter']}" if (spec["row_filter"] and has_region) else ""
            out.append(f"CREATE OR REPLACE VIEW `{project}.{view_ds}.{t}` AS\nSELECT {_select_list(meta, spec['mask_pii'], 'bigquery')}\nFROM `{project}.{dataset}.{t}` {where};")
        out.append("")
    # Native row access policies on base tables (for users who query base tables directly)
    for role, spec in pol["roles"].items():
        if spec["row_filter"]:
            for t, meta in meta_all.items():
                if any(c["name"] == "region" for c in meta["columns"]):
                    out.append(f"CREATE OR REPLACE ROW ACCESS POLICY {role}_rows ON `{project}.{dataset}.{t}`\n"
                               f"GRANT TO ('group:{role.replace('_', '-')}@example.com') FILTER USING ({spec['row_filter']});")
    out.append("\n-- Column-level security: attach Data Catalog policy tags to PII columns (schema JSON for `bq update`).")
    for t, meta in meta_all.items():
        for c in meta["columns"]:
            if c["classification"]:
                out.append(f"-- {t}.{c['name']}: policy tag 'PII/{c['classification']['pii']}'  (taxonomy: projects/{project}/locations/us/taxonomies/TAXONOMY_ID)")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    print(build_role_databases())
    p = C.ROOT / "sql" / "generated" / "bigquery_governance.sql"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(bigquery_ddl())
    print("wrote", p)
